import AppKit
import Combine

enum ClipboardPayload: Equatable {
    case text(String)
    case url(URL)
    case image(Data)
    case files([URL])

    var byteCount: Int {
        switch self {
        case .text(let text): text.utf8.count
        case .url(let url): url.absoluteString.utf8.count
        case .image(let data): data.count
        case .files(let urls): urls.reduce(0) { $0 + $1.absoluteString.utf8.count }
        }
    }
    var title: String {
        switch self {
        case .text(let text): String(text.prefix(160))
        case .url(let url): url.absoluteString
        case .image: String(localized: "Image")
        case .files(let urls): urls.count == 1 ? urls[0].lastPathComponent : String(localized: "\(urls.count) files")
        }
    }
    var symbol: String {
        switch self {
        case .text: "text.alignleft"
        case .url: "link"
        case .image: "photo"
        case .files: "doc.on.doc"
        }
    }
}

struct ClipboardEntry: Identifiable, Equatable {
    let id: UUID
    let payload: ClipboardPayload
    let createdAt: Date
    let sourceBundleID: String?
    var isFavorite: Bool
}

@MainActor
final class ClipboardModel: ObservableObject {
    @Published private(set) var items: [ClipboardEntry] = []
    @Published private(set) var enabled = false
    @Published var searchQuery = ""
    @Published var favoritesOnly = false
    @Published private(set) var status = String(localized: "Clipboard history is off")
    @Published var excludedBundleIDs: String {
        didSet { defaults.set(excludedBundleIDs, forKey: "clipboardExcludedBundleIDs") }
    }
    private let defaults: UserDefaults
    private let pasteboard: NSPasteboard
    private var timer: AnyCancellable?
    private var lastChange = -1
    private let maximumCount = 100
    private let maximumEntryBytes = 5 * 1_024 * 1_024
    private let maximumTotalBytes = 32 * 1_024 * 1_024
    private static let confidentialTypes = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType", "de.petermaurer.TransientPasteboardType",
        "com.agilebits.onepassword"
    ]
    private static let passwordManagers = [
        "com.1password.1password", "com.agilebits.onepassword7", "com.agilebits.onepassword-osx",
        "com.bitwarden.desktop", "org.keepassxc.keepassxc", "com.dashlane.dashlane", "com.lastpass.lastpass",
        "com.apple.passwords", "com.apple.keychainaccess"
    ]

    init(defaults: UserDefaults = .standard, pasteboard: NSPasteboard = .general) {
        self.defaults = defaults
        self.pasteboard = pasteboard
        excludedBundleIDs = defaults.string(forKey: "clipboardExcludedBundleIDs") ?? ""
        // History is memory-only and starts paused at every launch. No clipboard
        // content is accessed until the user explicitly enables collection.
    }

    var filteredItems: [ClipboardEntry] {
        items.filter { entry in
            (!favoritesOnly || entry.isFavorite) &&
            (searchQuery.isEmpty || entry.payload.title.localizedCaseInsensitiveContains(searchQuery))
        }
    }

    func setEnabled(_ enabled: Bool) {
        self.enabled = enabled
        timer = nil
        if enabled {
            lastChange = pasteboard.changeCount
            status = String(localized: "Collecting new copies on this Mac")
            timer = Timer.publish(every: 1, tolerance: 0.2, on: .main, in: .common).autoconnect()
                .sink { [weak self] _ in self?.poll() }
        } else {
            status = String(localized: "Clipboard history is paused")
        }
    }

    func clear() {
        items.removeAll()
        status = enabled ? String(localized: "History cleared; collecting new copies") : String(localized: "History cleared")
    }
    func remove(_ id: UUID) { items.removeAll { $0.id == id } }
    func toggleFavorite(_ id: UUID) {
        guard let index = items.firstIndex(where: { $0.id == id }) else { return }
        items[index].isFavorite.toggle()
    }

    /// Copies the saved value to the pasteboard. Pasting into another app remains
    /// an explicit user action and does not require Accessibility permission.
    func restore(_ entry: ClipboardEntry) {
        pasteboard.clearContents()
        switch entry.payload {
        case .text(let text): pasteboard.setString(text, forType: .string)
        case .url(let url): pasteboard.writeObjects([url as NSURL])
        case .image(let data):
            if let image = NSImage(data: data) { pasteboard.writeObjects([image]) }
        case .files(let urls): pasteboard.writeObjects(urls.map { $0 as NSURL })
        }
        lastChange = pasteboard.changeCount
        status = String(localized: "Copied to clipboard")
    }

    private func poll() {
        guard enabled, pasteboard.changeCount != lastChange else { return }
        lastChange = pasteboard.changeCount
        let source = NSWorkspace.shared.frontmostApplication?.bundleIdentifier
        guard !Self.shouldExclude(sourceBundleID: source, userExclusions: excludedBundleIDs) else { return }
        guard !Self.shouldIgnorePasteboardTypes((pasteboard.types ?? []).map(\.rawValue)) else { return }
        // Check each item as well, so a confidential secondary representation
        // cannot bypass the pasteboard-level check.
        guard !(pasteboard.pasteboardItems ?? []).contains(where: { item in
            Self.shouldIgnorePasteboardTypes(item.types.map(\.rawValue))
        }) else { return }

        let payload: ClipboardPayload?
        if let urls = pasteboard.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL], !urls.isEmpty {
            payload = .files(Array(urls.prefix(100)))
        } else if let data = pasteboard.data(forType: .png) ?? pasteboard.data(forType: .tiff), !data.isEmpty {
            payload = .image(data)
        } else if let string = pasteboard.string(forType: .URL), let url = URL(string: string) {
            payload = .url(url)
        } else if let text = pasteboard.string(forType: .string), !text.isEmpty {
            payload = .text(text)
        } else { payload = nil }
        guard let payload else { return }
        add(payload, sourceBundleID: source)
    }

    // Pure policy entry points make privacy and retention testable without
    // reading the user's clipboard.
    static func shouldIgnorePasteboardTypes(_ types: [String]) -> Bool {
        !Set(types).isDisjoint(with: confidentialTypes)
    }

    static func shouldExclude(sourceBundleID: String?, userExclusions: String) -> Bool {
        guard let source = sourceBundleID?.lowercased() else { return true }
        let additional = userExclusions.split(whereSeparator: { $0 == "," || $0 == "\n" })
            .map { $0.trimmingCharacters(in: .whitespacesAndNewlines).lowercased() }
        return passwordManagers.contains(source) || additional.contains(source)
    }

    func add(_ payload: ClipboardPayload, sourceBundleID: String?) {
        guard payload.byteCount <= maximumEntryBytes else {
            status = String(localized: "Skipped a clipboard item larger than 5 MB")
            return
        }
        if let existing = items.firstIndex(where: { $0.payload == payload }) {
            let item = items.remove(at: existing)
            items.insert(item, at: 0)
            return
        }
        while items.count >= maximumCount || items.reduce(0, { $0 + $1.payload.byteCount }) + payload.byteCount > maximumTotalBytes {
            guard let index = items.lastIndex(where: { !$0.isFavorite }) else {
                status = String(localized: "History is full of favorites. Remove one to keep new copies.")
                return
            }
            items.remove(at: index)
        }
        items.insert(ClipboardEntry(id: UUID(), payload: payload, createdAt: .now, sourceBundleID: sourceBundleID, isFavorite: false), at: 0)
        status = String(localized: "Collecting new copies on this Mac")
    }
}
